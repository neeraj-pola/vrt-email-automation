"""
Lead data model — mirrors CLAUDE.md §4 exactly.

Field groups (kept distinct on purpose, see §4/§10):
  - Imported from Excel (contact + company data)
  - Outreach tracking (deterministic pipeline state)
  - AI-driven, automated (ai_response_classification, requested_availability)
  - AI-proposed, staff-confirmable (qualified_status + qualified_status_source)
  - Company-facing, manual only (crm_status, sale_status, notes, scheduled_call_time)
  - Draft state (current draft shown on the dashboard)
"""
from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Optional
from uuid import uuid4

from pydantic import BaseModel, ConfigDict, EmailStr, Field, field_serializer


class EmailStatus(str, Enum):
    not_sent = "not_sent"
    sent = "sent"
    bounced = "bounced"
    unsubscribed = "unsubscribed"
    exhausted = "exhausted"


class AIResponseClassification(str, Enum):
    pending = "pending"
    interested = "interested"
    not_interested = "not_interested"
    unclear = "unclear"


class QualifiedStatus(str, Enum):
    unset = "unset"
    qualified = "qualified"
    not_qualified = "not_qualified"


class QualifiedStatusSource(str, Enum):
    ai = "ai"
    staff = "staff"


class DraftVersionSource(str, Enum):
    initial = "initial"
    manual = "manual"
    chatbot = "chatbot"
    pipeline = "pipeline"  # auto-generated by the outreach pipeline for a stage transition


class DraftVersion(BaseModel):
    """
    A superseded draft, kept so staff can go back to it -- AND so later
    stages have real conversation context instead of writing in a vacuum.
    Snapshotted whenever the *current* draft is about to be overwritten:
    a manual edit, a chatbot rewrite, a regeneration (see
    app/pipeline/draft_generation.py), or the automatic pipeline moving a
    lead to its next stage -- initial -> follow-up 1 -> follow-up 2, etc.
    (see app/pipeline/outreach_graph.py).
    """
    subject: str
    body_html: str
    source: DraftVersionSource
    # Human label for what this version actually was -- "Initial outreach",
    # "Follow-up 1", "Manual edit", "Chatbot rewrite" -- shown in the
    # dashboard's version dropdown so staff can tell them apart at a glance,
    # not just by timestamp. Optional/blank for older snapshots taken before
    # this field existed.
    stage: str = ""
    # Whether this version actually went out to the lead, or was drafted
    # (pipeline-pregenerated, or a manual/chatbot edit) and then superseded
    # before ever being sent -- e.g. a pre-drafted follow-up 2 that gets
    # overwritten when the lead replies first. The dashboard shows "(unsent)"
    # for these so staff don't mistake a draft that never went out for one
    # that did.
    sent: bool = False
    # Timezone-AWARE, unlike the rest of the model's naive-UTC timestamps
    # (see storage_service._row_to_lead) -- this one is never compared
    # against other datetimes in Python, only ever serialized out to the
    # frontend, so it needs an explicit UTC offset in the JSON. Without one,
    # `new Date(...)` in the browser parses a bare "2026-09-01T15:34:00" as
    # LOCAL time instead of UTC, showing a version as hours in the future.
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class Lead(BaseModel):
    id: str = Field(default_factory=lambda: str(uuid4()))
    created_time: datetime

    # Lead-provided data (imported from the LinkedIn-style connections export)
    first_name: Optional[str] = None
    last_name: Optional[str] = None
    full_name: str  # "First Last" -- derived at import; used everywhere a display name is needed
    email: EmailStr
    linkedin_url: Optional[str] = None
    company: Optional[str] = None
    position: Optional[str] = None
    employee_count: Optional[str] = None  # kept as text: exports carry ranges like "51-200"
    location: Optional[str] = None

    # Outreach tracking
    thread_id: Optional[str] = None
    last_sent_at: Optional[datetime] = None
    follow_up_count: int = 0
    email_status: EmailStatus = EmailStatus.not_sent

    # AI-driven, automated
    ai_response_classification: Optional[AIResponseClassification] = None
    requested_availability: Optional[str] = None
    # The lead's latest reply, verbatim, and when it arrived -- so staff can
    # read what the lead actually said right next to the AI's read of it.
    last_reply_text: Optional[str] = None
    last_reply_at: Optional[datetime] = None
    # Set the moment a lead clicks the corresponding link in the email
    # footer -- a real deliberate click, unlike open-pixel tracking, so a
    # trustworthy engagement signal even before any reply. Tracked
    # separately (not one combined field) so staff can see which specific
    # call-to-action landed. See app/api/routes_public.py's /click redirect.
    website_clicked_at: Optional[datetime] = None
    get_started_clicked_at: Optional[datetime] = None

    # AI-proposed, staff-confirmable
    qualified_status: QualifiedStatus = QualifiedStatus.unset
    qualified_status_source: Optional[QualifiedStatusSource] = None
    qualified_status_reasoning: Optional[str] = None  # shown to staff alongside the proposal

    # Company-facing, manual only
    crm_status: Optional[str] = None
    sale_status: Optional[str] = None
    notes: Optional[str] = None
    scheduled_call_time: Optional[datetime] = None

    # Draft state
    # current_draft_body_html holds only the AI/staff-authored inner content
    # (a few paragraphs) -- NOT the full email shell. The branded header,
    # portfolio showcase, and footer/unsubscribe link are applied at
    # send/preview time by app/services/email_template.py, so staff (and the
    # chatbot) only ever edit the actual message, not a large HTML template.
    current_draft_subject: Optional[str] = None
    current_draft_body_html: Optional[str] = None
    draft_locked: bool = False
    # Why the current draft says what it says, for staff: which of the 27
    # challenges it was framed around and what that was based on.
    personalization_note: Optional[str] = None
    draft_history: list[DraftVersion] = Field(default_factory=list)

    model_config = ConfigDict(use_enum_values=False)

    # created_time/last_sent_at/scheduled_call_time are kept naive UTC
    # internally (see storage_service._row_to_lead -- everything downstream
    # compares them against naive datetime.utcnow()). But sent to the
    # frontend as bare JSON without a UTC marker, `new Date(...)` in the
    # browser parses them as LOCAL time instead of UTC -- e.g. a lead sent
    # at 15:34 UTC would show as "sent at 15:34" in a browser already in
    # EST, hours in the future. Stamp the UTC offset only at the JSON
    # boundary; the naive value used for internal comparisons is untouched.
    @field_serializer("created_time", "last_sent_at", "scheduled_call_time", "last_reply_at",
                       "website_clicked_at", "get_started_clicked_at", when_used="json")
    def _serialize_as_utc(self, value: Optional[datetime]) -> Optional[str]:
        if value is None:
            return None
        if value.tzinfo is None:
            value = value.replace(tzinfo=timezone.utc)
        return value.isoformat()
